"""
Settings for Codebase DNA.

Kept deliberately small: one app (``dna``), SQLite by default, and a few
environment variables for anything that changes between machines.
"""

import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def env_bool(name, default=False):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


